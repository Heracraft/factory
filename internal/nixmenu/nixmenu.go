// Package nixmenu is the catalog behind GET /catalog and the renderer that
// turns a menu selection into a home-manager fragment (docs/features/
// config.md "Menu versus fragment"). Workstream 12 owns the catalog
// contents and format; this package is the api's view of it: package and
// program entries render into `home.packages` and `programs.*` lines of
// one generated fragment.
package nixmenu

import (
	"errors"
	"fmt"
	"sort"
	"strings"
)

// Item is one catalog entry as GET /catalog returns it.
type Item struct {
	ID          string   `json:"id"`
	Label       string   `json:"label"`
	Group       string   `json:"group"`
	Description string   `json:"description"`
	Kind        string   `json:"kind"`
	Options     []Option `json:"options,omitempty"`
	hm          func(opts map[string]string) string
}

// Option is a per-item choice.
type Option struct {
	ID      string   `json:"id"`
	Values  []string `json:"values"`
	Default string   `json:"default"`
}

// Selection is what PUT /config {menu} carries: `[{id, options}]`.
type Selection []Selected

// Selected is one chosen item.
type Selected struct {
	ID      string            `json:"id"`
	Options map[string]string `json:"options,omitempty"`
}

// Header is the first line of every generated fragment.
const Header = "# generated by repose from your menu selection; edit with repose config edit to take over"

// ErrUnknownItem is returned for an id outside the catalog.
var ErrUnknownItem = errors.New("unknown catalog item")

// ErrBadOption is returned for an option value outside the catalog.
var ErrBadOption = errors.New("invalid option value")

func pkg(id, label, group, desc, attr string) Item {
	return Item{ID: id, Label: label, Group: group, Description: desc, Kind: "package", hm: func(map[string]string) string { return "pkgs." + attr }}
}


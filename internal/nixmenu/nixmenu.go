// Catalog returns the catalog in id order.
func Catalog() []Item {
	out := make([]Item, len(catalog))
	copy(out, catalog)
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out
}

func find(id string) (Item, bool) {
	for _, it := range catalog {
		if it.ID == id {
			return it, true
		}
	}
	return Item{}, false
}

// Validate checks every id and option against the catalog.
func Validate(sel Selection) error {
	for _, s := range sel {
		it, ok := find(s.ID)
		if !ok {
			return fmt.Errorf("%w: %s", ErrUnknownItem, s.ID)
		}
		for name, val := range s.Options {
			var opt *Option
			for i := range it.Options {
				if it.Options[i].ID == name {
					opt = &it.Options[i]
				}
			}
			if opt == nil {
				return fmt.Errorf("%w: %s has no option %s", ErrBadOption, s.ID, name)
			}
			valid := false
			for _, v := range opt.Values {
				valid = valid || v == val
			}
			if !valid {
				return fmt.Errorf("%w: %s.%s=%s", ErrBadOption, s.ID, name, val)
			}
		}
	}
	return nil
}

// Render turns a selection into a home-manager fragment.
func Render(sel Selection) (string, error) {
	if err := Validate(sel); err != nil {
		return "", err
	}
	var pkgs []string
	seen := map[string]bool{}
	for _, s := range sel {
		if seen[s.ID] {
			continue
		}
		seen[s.ID] = true
		it, _ := find(s.ID)
		opts := map[string]string{}
		for _, o := range it.Options {
			opts[o.ID] = o.Default
		}
		for k, v := range s.Options {
			opts[k] = v
		}
		pkgs = append(pkgs, "    "+it.hm(opts))
	}
	var b strings.Builder
	b.WriteString(Header + "\n")
	b.WriteString("{ pkgs, ... }:\n{\n")
	b.WriteString("  home.packages = [\n")
	b.WriteString(strings.Join(pkgs, "\n"))
	if len(pkgs) > 0 {
		b.WriteString("\n")
	}
	b.WriteString("  ];\n}\n")
	return b.String(), nil
}

// IsGenerated reports whether a fragment came from Render.
func IsGenerated(fragment string) bool {
	return strings.HasPrefix(fragment, Header)
}
